"""Prompt and few-shot examples for restriction extraction (Russian normative texts).

The examples were derived from СП 42.13330.2016 and reviewed for the project. ``value`` is encoded
as flat string attributes (``value_operator`` / ``value_number`` / ``value_unit`` /
``value_condition``) because langextract attributes are string-valued; the extractor parses them
back into a ``RestrictionValue``. A clause with conditional norms yields several extractions — one
per value — as in the second example.
"""

from __future__ import annotations

import langextract as lx

# The extraction class label carried on every restriction extraction.
RESTRICTION_CLASS = "ограничение"

# Seed of the controlled restriction-kind vocabulary. Extended dynamically at ingest time:
# a kind that matches none of the known ones (by alias or embedding similarity) is added with
# status "pending" for later review.
SEED_KINDS: list[str] = [
    "запрет_размещения",
    "запрет_использования",
    "минимальное_расстояние",
    "минимальная_ширина",
    "минимальная_доля_площади",
    "предельная_высота",
    "плотность_застройки",
    "требование_размещения",
]

PROMPT_DESCRIPTION = (
    "Извлеки из текста нормативные ограничения. Каждое ограничение — это тройка:\n"
    "- subject: краткое название сущности или территории, в контексте которой действует "
    "ограничение (например «санитарно-защитная зона», «микрорайон»);\n"
    "- object: на что накладывается ограничение, кратко (например «объекты пищевой "
    "промышленности», «озелененная территория»);\n"
    "- kind: вид ограничения из списка: " + ", ".join(SEED_KINDS) + ". "
    "Если ни один не подходит — предложи короткий новый снейк-кейс код вида ограничения.\n"
    "Если в ограничении есть количественный параметр, добавь атрибуты: value_operator "
    "(>=, <=, >, <, =), value_number (число), value_unit (единица измерения: м, %, эт.), "
    "value_condition (условие применимости, если оно есть).\n"
    "subject и object — названия объектов, не предложения и не названия показателей. "
    "Не записывай туда «минимально допустимая обеспеченность населения ...» или "
    "«расстояние до ...». Названия должны укладываться в 200 символов. Если краткое "
    "название невозможно выделить достоверно, сохрани исходное название полностью "
    "для ручного разбора; не обрезай фразу и не теряй норму ради лимита.\n"
    "Отдельно укажи measurement_kind: area_share (доля площади), count_share (доля "
    "количества), provision (обеспеченность или отношение к расчётной потребности), "
    "distance (расстояние между объектами), linear_size (ширина/высота/длина самого "
    "объекта), other (иной или неясный показатель). measurement_indicator — что именно "
    "измеряется; measurement_basis — база расчёта, дословно из нормы. Не переноси базу "
    "расчёта в value_condition: условие — например «для сельских поселений».\n"
    "Для area_share обязательно укажи measurement_numerator_entity (объект, чья площадь "
    "измеряется) и measurement_denominator_entity (территория, площадь которой принята "
    "за 100%). Проценты обеспеченности, автомобилизации, мест или населения НЕ являются "
    "долей площади. При неясной базе не выбирай area_share. Не путай ширину объекта "
    "с расстоянием между объектами, этаж размещения помещения с этажностью здания.\n"
    "Радиус разворота/поворота и диаметр — linear_size, а не distance. "
    "«Расчётный радиус», «значение радиуса», «уровень территориальной доступности» "
    "— показатели, не subject/object. Если реальные объекты не указаны, не придумывай "
    "их: используй measurement_kind=other и сохрани исходную формулировку. "
    "Для расстояния от входа укажи именно вход, а не всю территорию. Для расстояния "
    "между разъездными площадками укажи площадки с обеих сторон, а не проезд.\n"
    "В extraction_text сохрани точное полное предложение с объектом, показателем, "
    "числом и базой расчёта, а не только фразу «не менее 90%». "
    "Не извлекай ограничений, которых нет в тексте."
)


def _ex(text: str, attrs: dict[str, str]) -> lx.data.Extraction:
    return lx.data.Extraction(
        extraction_class=RESTRICTION_CLASS,
        extraction_text=text,
        attributes=attrs,
    )


