"""Wordings of norms for the Urban API types they mean.

Norms name objects in their own words («общеобразовательные организации»,
«краеведческий музей», «остановки НГПТ»). ``UrbanCatalog.resolve`` falls back to
these patterns only when a name is not a catalog name in any case or number, and
accepts the result only when exactly one catalog type matches.
"""

from __future__ import annotations

import re

# (pattern over a normalized name, canonical Urban API type name)
_ALIASES: tuple[tuple[str, str], ...] = (
    (r"детск\w*\s+сад|дошкольн\w*\s+(?:образоват|организац|учрежд)|\bясл", "Детский сад"),
    (
        r"(?<!спортивная )(?<!спортивной )(?<!спортивные )(?<!спортивных )"
        r"\bшкол(?!\w*\s+(?:искусств|музык|художеств|хореограф|спортив|олимпийск))"
        r"|общеобразоват|начального\s+общего|основного\s+общего|среднего\s+общего",
        "Школа",
    ),
    (r"детск\w*\s+дом|детей\s*-?\s*сирот|без\s+попечения\s+родител", "Детский дом-интернат"),
    (r"престарел|пожил\w*\s+(?:граждан|люд)", "Дом престарелых"),
    (r"поликлиник|амбулаторн", "Поликлиника"),
    (r"больниц|стационар", "Больница"),
    (r"аптек|аптечн", "Аптека"),
    (r"\bрын(?:ок|к)", "Рынок"),
    (r"остановк\w*|остановочн|\bнгпт\b", "Остановка наземного общественного транспорта"),
    (r"музе", "Музей"),
    (r"\bтеатр", "Театр"),
    (r"кинотеатр|кинозал", "Кинотеатр"),
    (r"(?:дом|дворц)\w*\s+культур|культурно\s*-?\s*досугов", "Дворец культуры"),
    (r"библиотек", "Библиотека"),
    (r"концертн\w*\s+зал", "Концертный зал"),
    (r"зоопарк", "Зоопарк"),
    (r"\bпарк(?!\w*\s+(?:аттракц|развлеч))(?!овк|овоч|инг)", "Парк"),
    (r"(?:спортивн|физкультурн)\w*\s+площадк", "Спортивная площадка"),
    (r"детск\w*\s+(?:игров\w*\s+)?площадк|площадк\w*\s+для\s+игр", "Детская площадка"),
    (
        r"спортивн\w*\s+(?:центр|комплекс|сооружен|зал|школ)|физкультурно\s*-?\s*оздоровит"
        r"|спортивно\s*-?\s*тренировоч|\bфок\b|\bдюсш\b",
        "Спортивный центр",
    ),
    (r"бассейн", "Бассейн"),
    (r"стадион", "Стадион"),
    (r"почтов|\bпочт", "Почтовое отделение"),
    (r"\bмфц\b|многофункциональн\w*\s+центр", "МФЦ"),
    (r"пожарн\w*\s+(?:депо|част|станц)", "Пожарная станция"),
    (r"кладбищ", "Кладбище"),
    (r"гостиниц|\bотел", "Гостиница"),
    (r"парковк|автостоянк|стоянк\w*\s+(?:автомоб|легков|транспорт)|машино\s*-?\s*мест", "Парковка"),
    (r"жил\w*\s+(?:дом|здани)|многоквартирн", "Жилой дом"),
    (r"автозаправочн|\bазс\b", "Автозаправочная станция"),
    (r"котельн", "Котельная"),
    (r"лагер", "Детский лагерь"),
    (r"колледж|техникум|средн\w*\s+профессиональн", "Учреждение среднего профессионального образования"),
    (r"\bвуз|высш\w*\s+(?:учебн|образоват)|университет", "Учреждение высшего профессионального образования"),
    (r"скор\w*\s+(?:медицинск\w*\s+)?помощ", "Станция скорой медицинской помощи"),
    (r"железнодорожн\w*\s+станц", "Железнодорожная станция"),
)

ALIASES: tuple[tuple[re.Pattern[str], str], ...] = tuple(
    (re.compile(pattern), name) for pattern, name in _ALIASES
)


def alias_names(normalized: str) -> list[str]:
    """Canonical type names whose wordings occur in ``normalized`` (in table order)."""
    return list(
        dict.fromkeys(name for pattern, name in ALIASES if pattern.search(normalized))
    )
